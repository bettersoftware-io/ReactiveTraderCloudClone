/**
 * The `geo` boot scene's hand-placed coordinate tables — DATA ONLY.
 *
 * Extracted mechanically from `packages/boot-splash/src/variants/bootGeo.ts`
 * (its `MAIN`/`GB`/`IRE`/`SIC`/`SAR`/`COR`/`DKZ` and `CITY` tables) rather
 * than retyped. ~310 lines of lon/lat pairs is precisely where a transposed
 * digit becomes a coastline with a spike in it that no unit test would notice,
 * so parsing the source makes that class of error impossible instead of merely
 * unlikely.
 *
 * Nothing here is worklet-marked: these are constants, read once and captured.
 * The projection into plane space lives in `geoGeometry.ts`.
 *
 * Landmass ORDER matters — `bootGeo.ts:406` builds its polygon list as
 * `[MAIN, GB, IRE, SIC, SAR, COR, DKZ]`, and the even-odd `inside()` test that
 * seeds the terrain mesh walks them in that order.
 */

/** A `[lon, lat]` pair, as the source tables store them. */
export type GeoLonLat = readonly [number, number];

/** One closed coastline polyline. */
export interface GeoLandmass {
  readonly name: string;
  readonly points: readonly GeoLonLat[];
}

/** A capital-city node: position, importance weight, label. */
export interface GeoCity {
  readonly lon: number;
  readonly lat: number;
  readonly importance: number;
  readonly name: string;
}

